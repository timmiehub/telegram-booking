/** Привести фразу к виду для сравнения. */
export function normalizeFaqText(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[?!.…,;:«»"'`]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

