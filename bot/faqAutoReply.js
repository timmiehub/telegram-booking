function compileIndex() {
  const byPhrase = new Map()
  const withPatterns = []
  for (const entry of FAQ_ENTRIES) {
    for (const p of entry.phrases || []) {
      byPhrase.set(normalizeFaqText(p), entry)
    }
    if (entry.patterns?.length) withPatterns.push(entry)
  }
  return { byPhrase, withPatterns }
}

const INDEX = compileIndex()

/**
 * @returns {{ id: string, reply: string } | null}
 */
export function matchFaqAutoReply(text) {
  const raw = String(text || '').trim()
  if (!raw || raw.length > 120) return null
  const n = normalizeFaqText(raw)
  if (!n || n.split(' ').length > 10) return null

  const exact = INDEX.byPhrase.get(n)
  if (exact) return { id: exact.id, reply: exact.reply() }

  for (const entry of INDEX.withPatterns) {
    for (const re of entry.patterns) {
      if (re.test(n)) return { id: entry.id, reply: entry.reply() }
    }
  }
  return null
}
