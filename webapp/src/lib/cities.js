const CITY_KEY = 'tb_client_city'

export function getSavedClientCity() {
  try {
    return localStorage.getItem(CITY_KEY) || ''
  } catch {
    return ''
  }
}

export function setSavedClientCity(city) {
  try {
    if (city) localStorage.setItem(CITY_KEY, city)
    else localStorage.removeItem(CITY_KEY)
  } catch {
    // ignore
  }
}

export function filterCities(query, limit = 12) {
  const q = String(query || '')
    .trim()
    .toLowerCase()
  if (!q) return RU_CITIES.slice(0, limit)
  return RU_CITIES.filter((c) => c.toLowerCase().includes(q)).slice(0, limit)
}

export function normalizeCity(name) {
  const raw = String(name || '').trim()
  if (!raw) return ''
  const hit = RU_CITIES.find((c) => c.toLowerCase() === raw.toLowerCase())
  return hit || raw
}
